// Light background + dark text — real product photography is almost always
// shot on a light/white backdrop, and (unlike a dark bg matching the app's
// own dark theme) this actually reads as a distinct image against the dark
// card/page chrome instead of disappearing into it.
const img = (label, bg = "eef1f6", fg = "1f2937") =>
  `https://placehold.co/900x700/${bg}/${fg}?text=${encodeURIComponent(label)}&font=raleway`;

const PLATFORMS = {
  amazon: "Amazon",
  flipkart: "Flipkart",
  croma: "Croma",
  reliance: "Reliance Digital",
  vijaySales: "Vijay Sales",
};

// Demo seller URLs point at each retailer's real search results page for the
// product name — honest (it actually resolves to something real) without
// pretending to be a specific live product listing we don't actually have.
function sellerUrl(platform, name) {
  const q = encodeURIComponent(name);
  const urls = {
    Amazon: `https://www.amazon.in/s?k=${q}`,
    Flipkart: `https://www.flipkart.com/search?q=${q}`,
    Croma: `https://www.croma.com/searchB?q=${q}`,
    "Reliance Digital": `https://www.reliancedigital.in/search?q=${q}`,
    "Vijay Sales": `https://www.vijaysales.com/search/${q}`,
  };
  return urls[platform];
}

function sellers(name, offers) {
  return offers.map(([platform, price, availability = true]) => ({
    platform,
    price,
    currency: "INR",
    url: sellerUrl(platform, name),
    availability,
  }));
}

